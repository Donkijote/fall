export function mountainPoints(points: MountainPoint[]) {
  return points.map(([horizontal, vertical]) => `${horizontal},${vertical}`).join(" ");
}

export function getMountainScale(width: number, height: number) {
  return Math.max(width / mountainFrame.width, height / mountainFrame.height);
}
